def flow_strategy(data):
    """Trend Following (Flow) Strategy"""
    close = data['close']
    ema_fast = close.ewm(span=20, adjust=False).mean()
    ema_slow = close.ewm(span=50, adjust=False).mean()

    price = close.iloc[-1]
    fast = ema_fast.iloc[-1]
    slow = ema_slow.iloc[-1]

    if fast > slow and price > fast:
        return "BUY"
    elif fast < slow and price < fast:
        return "SELL"
    else:
        return "HOLD"

def big_candle_filter(data):
    """Big Candle Filter"""
    high = data['high']
    low = data['low']

    candle_range = high.iloc[-1] - low.iloc[-1]
    avg_range = (high - low).rolling(14).mean().iloc[-1]

    if avg_range == 0 or avg_range != avg_range:
        return True

    if candle_range > avg_range * 1.8:
        return False
    return True

def doji_filter(data):
    """Doji Filter"""
    o = data['open'].iloc[-1]
    c = data['close'].iloc[-1]
    h = data['high'].iloc[-1]
    l = data['low'].iloc[-1]

    body = abs(c - o)
    candle_range = h - l

    if candle_range == 0:
        return False

    body_ratio = body / candle_range
    if body_ratio < 0.1:
        return False
    return True

def market_level_volatility_signal(data):
    """Market Level + Volatility Confirmation"""
    high = data['high']
    low = data['low']
    close = data['close']

    current_price = close.iloc[-1]
    recent_high = high.rolling(20).max().iloc[-1]
    recent_low = low.rolling(20).min().iloc[-1]
    atr = (high - low).rolling(14).mean().iloc[-1]

    if recent_high == recent_low:
        position_in_range = 0.5
    else:
        position_in_range = (current_price - recent_low) / (recent_high - recent_low)

    if position_in_range > 0.75:
        level_signal = "SELL"
    elif position_in_range < 0.25:
        level_signal = "BUY"
    else:
        level_signal = "HOLD"

    volatility_ok = bool(atr and atr > 0)

    return {
        "signal": level_signal,
        "price": round(float(current_price), 5),
        "level": round(float(position_in_range), 2),
        "volatility": round(float(atr), 5) if atr == atr else 0,
        "volatility_ok": volatility_ok,
    }


